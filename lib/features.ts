/**
 * 機能の入り口を出すか（公開版のスイッチ）
 *
 * ING_OR_TO_ENABLED: 「ing or to」の出題（ホームの入口・出題の画面・単語帳の札）
 *  - 公開前は、false。単語を入れるだけで整う「自動の入力補助」を売りにするので、自動で判定できない出題は、いったん隠す
 *  - データは、消さない（同梱の問題・単語の答え・CSV の列は、そのまま）。true に戻せば、元どおりに使える
 *  - 戻すときは、動詞の一覧を同梱して、答えを自動で下書きできるようにしてから、追加・編集の画面の入力欄も戻す
 */
export const ING_OR_TO_ENABLED = false;

/**
 * DRIVE_BACKUP_ENABLED: Google ドライブへの自動バックアップと、ドライブからの復元（設定の項目・起動時の自動保存・新しい端末での復元の案内）
 *  - 公開前は、false。Google Cloud の認証の設定と、ストア版での実機の確認が済んでいないため、最初の版では隠し、公開後の更新で足す
 *  - ファイルへの書き出しと、ファイルからの復元は、このスイッチに関係なく使える
 *  - true に戻すときは、プライバシーポリシーの「8-2. Google ドライブへのバックアップ」と、データセーフティの回答も戻す
 */
export const DRIVE_BACKUP_ENABLED = false;
